"""Non-production VTpass certification harness.

The default command only verifies the DOCUMENTED sandbox IBEDC test meter.
No customer balance, Payquick wallet, live VTPass account or physical
meter is modified. An optional sandbox /pay requires TWO explicit opt-ins.
"""
import argparse
import hashlib
import json
import os
import re
from datetime import datetime, timezone

import requests
from errors import ApiError
import vtpass


IBEDC_SANDBOX_METER = "1111111111111"
IBEDC_SERVICE = "ibadan-electric"


def sandbox_only():
    if vtpass.environment() != "sandbox":
        raise RuntimeError("Certification harness is sandbox-only; LIVE is prohibited")
    if not os.getenv("VTPASS_API_KEY") or not os.getenv("VTPASS_SECRET_KEY"):
        raise ApiError(503, "VTpass sandbox API key/secret key required")


def safe_fingerprint(value):
    return hashlib.sha256(str(value).encode()).hexdigest()[:16]


def check_public_service_list():
    public_key = os.getenv("VTPASS_PUBLIC_KEY", "")
    if not public_key:
        return {"status": "skipped", "reason": "VTPASS_PUBLIC_KEY not configured"}
    try:
        resp = requests.get(
            "https://sandbox.vtpass.com/api/services",
            params={"identifier": "electricity-bill"},
            headers={"api-key": os.environ["VTPASS_API_KEY"], "public-key": public_key},
            timeout=(5, 20),
        )
        resp.raise_for_status()
        payload = resp.json()
    except (requests.RequestException, ValueError) as exc:
        raise ApiError(502, "VTpass sandbox service-list request failed") from exc
    content = payload.get("content") if isinstance(payload, dict) else None
    ids = [s.get("serviceID") for s in content if isinstance(s, dict)] if isinstance(content, list) else []
    return {"status": "passed" if IBEDC_SERVICE in ids else "failed", "ibedc_listed": IBEDC_SERVICE in ids}


def verify_ibedc_sandbox():
    sandbox_only()
    result = vtpass.verify_meter(IBEDC_SERVICE, IBEDC_SANDBOX_METER)
    return {
        "status": "passed" if result["minimum_kobo"] >= 200000 else "failed",
        "service": IBEDC_SERVICE,
        "customer_name_present": bool(result.get("customer_name")),
        "minimum_kobo": result["minimum_kobo"],
        "verified_physical_meter": False,
    }


def status_probe(reference):
    sandbox_only()
    if not isinstance(reference, str) or not reference.startswith("20") or len(reference) != 44:
        raise ValueError("Supply a VTpass request_id generated by the Payquick sandbox harness")
    result = vtpass.requery(reference)
    status, token = vtpass.classify(result)
    return {
        "status": "observed", "provider_classification": status,
        "request_id_hash": safe_fingerprint(reference),
        "token_present": bool(token),
        "provider_code": str(result.get("code", ""))[:8],
        "physical_meter_loaded": False,
    }


def purchase_probe(*, amount_naira, phone, approved):
    sandbox_only()
    if not approved or os.getenv("VTPASS_SANDBOX_SPEND_APPROVED") != "true":
        raise ApiError(403, "Sandbox vending requires explicit CLI and environment approval")
    if type(amount_naira) is not int or not 2000 <= amount_naira <= 5000:
        raise ValueError("Sandbox probe amount must be whole naira between 2000 and 5000")
    if not isinstance(phone, str) or re.fullmatch(r"0[789][01]\d{8}", phone) is None:
        raise ValueError("Invalid sandbox phone")
    ref = vtpass.request_id()
    response = vtpass.buy_electricity(
        request_id_value=ref, disco=IBEDC_SERVICE, meter_number=IBEDC_SANDBOX_METER,
        amount_kobo=amount_naira * 100, phone=phone,
    )
    classification, token = vtpass.classify(response)
    return {
        "status": "observed", "request_id": ref, "classification": classification,
        "token_present": bool(token), "provider_code": str(response.get("code", ""))[:8],
        "physical_meter_loaded": False,
        "instructions": "Save request ID in secure operator log; inspect VTpass wallet and call --requery to reconcile.",
    }


def main():
    parser = argparse.ArgumentParser(description="Explicit VTpass SANDBOX certification")
    parser.add_argument("--probe", choices=["verify", "requery", "purchase"], default="verify")
    parser.add_argument("--request-id")
    parser.add_argument("--amount-naira", type=int, default=2000)
    parser.add_argument("--phone")
    parser.add_argument("--approve-sandbox-vend", action="store_true")
    args = parser.parse_args()
    sandbox_only()
    if args.probe == "verify":
        results = {"meter": verify_ibedc_sandbox(), "catalogue": check_public_service_list()}
    elif args.probe == "requery":
        results = status_probe(args.request_id)
    else:
        results = purchase_probe(
            amount_naira=args.amount_naira, phone=args.phone,
            approved=args.approve_sandbox_vend,
        )
    print(json.dumps({
        "certification": "provisional_until_review", "environment": "sandbox",
        "checked_at": datetime.now(timezone.utc).isoformat(), "results": results,
    }, sort_keys=True))


if __name__ == "__main__":
    main()
